"""Record the resolved Windows runtime/build closure from a reviewed environment."""

from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]


def main():
    roots = [
        Requirement(line)
        for line in (ROOT / "requirements.txt").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    roots.append(Requirement("pyinstaller==6.22.3"))
    seen, versions = set(), {}
    while roots:
        requirement = roots.pop()
        distribution = metadata.distribution(requirement.name)
        name = distribution.metadata["Name"]
        extras = requirement.extras or {""}
        key = (name.casefold(), tuple(sorted(extras)))
        if key in seen:
            continue
        seen.add(key)
        versions[name] = distribution.version
        for dependency in distribution.requires or []:
            item = Requirement(dependency)
            if item.marker is None or any(
                item.marker.evaluate({"extra": extra}) for extra in extras
            ):
                roots.append(item)
    text = "# Resolved Windows x64 runtime/build environment; generated by tools/lock_dependencies.py.\n"
    text += "".join(
        f"{name}=={version}\n"
        for name, version in sorted(versions.items(), key=lambda x: x[0].casefold())
    )
    (ROOT / "requirements.lock").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
